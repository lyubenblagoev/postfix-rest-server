CREATE TABLE domains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    name VARCHAR(255) NOT NULL
);
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    username VARCHAR(255),
    password VARCHAR(255),
    domain_id BIGINT
);
CREATE TABLE aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    alias VARCHAR(255),
    email VARCHAR(255),
    domain_id BIGINT
);
CREATE TABLE recipient_bccs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    receiver_email_address VARCHAR(255),
    account_id BIGINT
);
CREATE TABLE sender_bccs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    receiver_email_address VARCHAR(255),
    account_id BIGINT
);
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    name VARCHAR(255)
);
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL
);
CREATE TABLE user_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    created TIMESTAMP,
    updated TIMESTAMP,
    refresh_token VARCHAR(255),
    refresh_token_expiration_date TIMESTAMP,
    remote_address VARCHAR(255),
    type VARCHAR(255),
    os VARCHAR(255),
    user_id BIGINT
);
CREATE TABLE users_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL
);

