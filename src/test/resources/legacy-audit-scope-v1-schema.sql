CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(32) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    actor_user_id BIGINT,
    actor_username VARCHAR(320) NOT NULL,
    account_id BIGINT,
    domain_id BIGINT
);
CREATE TABLE audit_log_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_log_id BIGINT NOT NULL,
    field_name VARCHAR(128) NOT NULL,
    old_value VARCHAR(2048),
    new_value VARCHAR(2048)
);
CREATE TABLE audit_log_scope_backfill (
    id BIGINT PRIMARY KEY,
    backfill_version INT NOT NULL,
    completed_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_audit_entity_history ON audit_logs (entity_type, entity_id, occurred_at);
CREATE INDEX idx_audit_recent ON audit_logs (occurred_at);
CREATE INDEX idx_audit_domain_scope ON audit_logs (domain_id, occurred_at);
CREATE INDEX idx_audit_account_scope ON audit_logs (account_id, occurred_at);

